package com.airops.flight;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

/**
 * Model class that represents a single flight record.
 * It holds the data for one row of the "flights" table.
 */
public class Flight {

    private int flightId;
    private String flightNumber;
    private String airlineName;
    private String source;
    private String destination;
    private LocalDateTime departureTime;
    private LocalDateTime arrivalTime;
    private String status;
    private String gateNumber;
    private int delayMinutes;
    private String delayReason;

    // Formatter used only for printing dates in a readable way
    private static final DateTimeFormatter DATE_FORMAT =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");

    // Default constructor
    public Flight() {
        this.status = "SCHEDULED";
        this.delayMinutes = 0;
    }

    /**
     * Constructor used when creating a brand new flight.
     * The flightId is generated by the database, so it is not required here.
     */
    public Flight(String flightNumber, String airlineName, String source,
                  String destination, LocalDateTime departureTime,
                  LocalDateTime arrivalTime) {
        this.flightNumber = flightNumber;
        this.airlineName = airlineName;
        this.source = source;
        this.destination = destination;
        this.departureTime = departureTime;
        this.arrivalTime = arrivalTime;
        this.status = "SCHEDULED";
        this.gateNumber = null;
        this.delayMinutes = 0;
        this.delayReason = null;
    }

    /**
     * Constructor used when reading an existing flight from the database.
     * It contains every column value, including the generated flightId.
     */
    public Flight(int flightId, String flightNumber, String airlineName,
                  String source, String destination,
                  LocalDateTime departureTime, LocalDateTime arrivalTime,
                  String status, String gateNumber, int delayMinutes,
                  String delayReason) {
        this.flightId = flightId;
        this.flightNumber = flightNumber;
        this.airlineName = airlineName;
        this.source = source;
        this.destination = destination;
        this.departureTime = departureTime;
        this.arrivalTime = arrivalTime;
        this.status = status;
        this.gateNumber = gateNumber;
        this.delayMinutes = delayMinutes;
        this.delayReason = delayReason;
    }

    public int getFlightId() {
        return flightId;
    }

    public void setFlightId(int flightId) {
        this.flightId = flightId;
    }

    public String getFlightNumber() {
        return flightNumber;
    }

    public void setFlightNumber(String flightNumber) {
        this.flightNumber = flightNumber;
    }

    public String getAirlineName() {
        return airlineName;
    }

    public void setAirlineName(String airlineName) {
        this.airlineName = airlineName;
    }

    public String getSource() {
        return source;
    }

    public void setSource(String source) {
        this.source = source;
    }

    public String getDestination() {
        return destination;
    }

    public void setDestination(String destination) {
        this.destination = destination;
    }

    public LocalDateTime getDepartureTime() {
        return departureTime;
    }

    public void setDepartureTime(LocalDateTime departureTime) {
        this.departureTime = departureTime;
    }

    public LocalDateTime getArrivalTime() {
        return arrivalTime;
    }

    public void setArrivalTime(LocalDateTime arrivalTime) {
        this.arrivalTime = arrivalTime;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getGateNumber() {
        return gateNumber;
    }

    public void setGateNumber(String gateNumber) {
        this.gateNumber = gateNumber;
    }

    public int getDelayMinutes() {
        return delayMinutes;
    }

    public void setDelayMinutes(int delayMinutes) {
        this.delayMinutes = delayMinutes;
    }

    public String getDelayReason() {
        return delayReason;
    }

    public void setDelayReason(String delayReason) {
        this.delayReason = delayReason;
    }

    /**
     * Prints the flight details in a clean, readable format.
     */
    public void displayFlightDetails() {
        System.out.println("----------------------------------------");
        System.out.println("Flight ID      : " + flightId);
        System.out.println("Flight Number  : " + flightNumber);
        System.out.println("Airline        : " + airlineName);
        System.out.println("Source         : " + source);
        System.out.println("Destination    : " + destination);
        System.out.println("Departure Time : " +
                (departureTime == null ? "-" : departureTime.format(DATE_FORMAT)));
        System.out.println("Arrival Time   : " +
                (arrivalTime == null ? "-" : arrivalTime.format(DATE_FORMAT)));
        System.out.println("Status         : " + status);
        System.out.println("Gate Number    : " +
                (gateNumber == null || gateNumber.isEmpty() ? "Not Assigned" : gateNumber));
        System.out.println("Delay Minutes  : " + delayMinutes);
        System.out.println("Delay Reason   : " +
                (delayReason == null || delayReason.isEmpty() ? "-" : delayReason));
        System.out.println("----------------------------------------");
    }

    @Override
    public String toString() {
        return "Flight ID: " + flightId +
                "\nFlight Number: " + flightNumber +
                "\nAirline: " + airlineName +
                "\nRoute: " + source + " -> " + destination +
                "\nDeparture: " + (departureTime == null ? "-" : departureTime.format(DATE_FORMAT)) +
                "\nArrival: " + (arrivalTime == null ? "-" : arrivalTime.format(DATE_FORMAT)) +
                "\nStatus: " + status +
                "\nGate: " + (gateNumber == null || gateNumber.isEmpty() ? "Not Assigned" : gateNumber) +
                "\nDelay: " + delayMinutes + " min" +
                (delayReason == null || delayReason.isEmpty() ? "" : " (" + delayReason + ")");
    }
}